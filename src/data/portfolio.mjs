export function filterProjects(query = "", category = "All projects") {
  const terms = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  return projects.filter((project) => {
    const text = [
      project.name,
      project.summary,
      project.kind,
      project.category,
      ...project.tech,
      ...project.practices,
    ]
      .join(" ")
      .toLowerCase();
    return (
      (category === categories[0] || project.category === category) &&
      terms.every((term) => text.includes(term))
    );
  });
}
